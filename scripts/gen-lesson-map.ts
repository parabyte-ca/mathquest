// Writes shared/lessons/map.ts: which grade group each lesson lives in, so the web app can fetch just that group.
// Run with `npm run gen:lessons` after adding a lesson. tests/lessons.test.ts fails if the file is out of date.
import { writeFileSync } from 'node:fs';
import { LESSON_BUCKETS } from '../shared/lessons/index.js';

export function lessonMapSource(): string {
  const rows: string[] = [];
  for (const [bucket, lessons] of Object.entries(LESSON_BUCKETS)) for (const l of lessons) rows.push(`  '${l.id}': '${bucket}',`);
  return `// GENERATED by scripts/gen-lesson-map.ts (npm run gen:lessons). Do not edit by hand.\nimport type { LessonBucket } from './index.js';\n\nexport const LESSON_BUCKET_OF: Record<string, LessonBucket> = {\n${rows.join('\n')}\n};\n`;
}

if (process.argv[1]?.endsWith('gen-lesson-map.ts')) {
  writeFileSync(new URL('../shared/lessons/map.ts', import.meta.url), lessonMapSource());
  console.log('wrote shared/lessons/map.ts');
}
